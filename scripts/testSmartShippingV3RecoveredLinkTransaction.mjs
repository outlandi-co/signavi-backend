import "dotenv/config"
import assert from "node:assert/strict"
import mongoose from "mongoose"
import Order from "../models/Order.js"
import PaymentOperation from "../models/SmartShippingV3PaymentOperation.js"
import {
  recordV3RecoveredLinkTransaction
} from "../utils/smartShippingV3RecoveredLinkTransaction.js"

const database = "signavi_shipping_v3_recovery_tests"
const protectedId = "6addc6f674d8362634569095"
const ids = [
  new mongoose.Types.ObjectId(),
  new mongoose.Types.ObjectId(),
  new mongoose.Types.ObjectId(),
  new mongoose.Types.ObjectId(),
  new mongoose.Types.ObjectId()
]
const owner = `recovery-test-${ids[0]}`
const claim = new Date(Date.now() - 120000)
const expiry = new Date(Date.now() - 60000)
const linkId = `TEST-LINK-${ids[0]}`
const squareOrderId = `TEST-SQUARE-${ids[0]}`

let connected = false

const operationFor = id => ({
  orderId: id,
  environment: "sandbox",
  status: "reconciliation_required",
  requestOwner: owner,
  squareCreationAttemptClaimedAt: claim,
  amountCents: 100,
  idempotencyKey: `signavi-v3-sandbox-${id}`,
  checkoutReferenceId: `signavi-v3-sandbox-${id}`,
  squarePaymentLinkId: "",
  squareOrderId: "",
  paymentUrl: ""
})

const orderFor = (id, paid = false) => ({
  _id: id,
  status: "payment_required",
  paymentStatus: paid ? "paid" : "unpaid",
  currency: "USD",
  squareEnvironment: "sandbox",
  squareExpectedAmountCents: 100,
  squarePaymentLinkId: "",
  squareOrderId: ""
})

const verified = {
  verified: true,
  checkoutReferenceVerified: true,
  amountCents: 100,
  squarePaymentLinkId: linkId,
  squareOrderId,
  paymentUrl: "https://sandbox.square.link/u/synthetic-test"
}

try {
  assert.equal(process.env.SQUARE_ENVIRONMENT, "sandbox")
  assert.ok(process.env.MONGO_URI, "MONGO_URI is required")
  assert.notEqual(database, "signavi_shipping_v3_dev")
  assert.ok(ids.every(id => String(id) !== protectedId))

  // Set only in this Node process, never globally in PowerShell.
  process.env.NODE_ENV = "test"
  process.env.SMART_SHIPPING_V3_RECOVERY_TEST_WRITES = "true"

  await mongoose.connect(process.env.MONGO_URI, {
    dbName: database,
    serverSelectionTimeoutMS: 10000
  })
  connected = true
  assert.equal(mongoose.connection.db.databaseName, database)

  const orders = Order.collection
  const operations = PaymentOperation.collection
  const locks = mongoose.connection.db.collection(
    "smart_shipping_v3_checkout_locks"
  )

  // Only synthetic IDs generated by this test are ever inserted.
  for (let i = 0; i < ids.length; i++) {
    const id = ids[i]
    await orders.insertOne(orderFor(id, i === 1))
    await operations.insertOne(operationFor(id))
    await locks.insertOne({
      _id: id,
      owner,
      expiresAt: expiry,
      ownershipChecks: 0
    })
  }

  const result = await recordV3RecoveredLinkTransaction({
    orderId: String(ids[0]),
    owner,
    expectedPaymentLinkId: linkId,
    verified
  })

  assert.equal(result.paymentLinkRecorded, true)
  assert.equal(result.customerPaymentConfirmed, false)

  const successOperation = await operations.findOne({
    orderId: ids[0]
  })
  const successOrder = await orders.findOne({ _id: ids[0] })
  const successLock = await locks.findOne({ _id: ids[0] })

  assert.equal(successOperation.status, "completed")
  assert.equal(successOperation.squarePaymentLinkId, linkId)
  assert.equal(successOperation.squareOrderId, squareOrderId)
  assert.equal(successOperation.paymentUrl, verified.paymentUrl)
  assert.equal(
    successOperation.squareCreationAttemptClaimedAt.getTime(),
    claim.getTime()
  )
  assert.equal(successOperation.requestOwner, owner)
  assert.equal(successOrder.paymentStatus, "unpaid")
  assert.equal(successOrder.status, "payment_required")
  assert.equal(successLock.owner, owner)
  assert.equal(successLock.expiresAt.getTime(), expiry.getTime())

  console.log("SYNTHETIC RECOVERY SUCCESS: PASS")
  console.log("UNPAID ORDER PRESERVED: PASS")
  console.log("ORIGINAL CLAIM AND EXPIRED LOCK PRESERVED: PASS")

  // The same existing Square link must not be recorded twice.
  const beforeRepeat = await operations.findOne({
    orderId: ids[0]
  })
  const beforeRepeatLock = await locks.findOne({
    _id: ids[0]
  })

  await assert.rejects(
    recordV3RecoveredLinkTransaction({
      orderId: String(ids[0]),
      owner,
      expectedPaymentLinkId: linkId,
      verified
    }),
    /eligibility rejected/
  )

  const afterRepeat = await operations.findOne({
    orderId: ids[0]
  })
  const afterRepeatLock = await locks.findOne({
    _id: ids[0]
  })

  assert.equal(afterRepeat.status, "completed")
  assert.equal(
    afterRepeat.squarePaymentLinkId,
    beforeRepeat.squarePaymentLinkId
  )
  assert.equal(
    afterRepeat.squareCreationAttemptClaimedAt.getTime(),
    beforeRepeat.squareCreationAttemptClaimedAt.getTime()
  )
  assert.equal(
    afterRepeatLock.ownershipChecks,
    beforeRepeatLock.ownershipChecks
  )

  console.log("DUPLICATE RECOVERY REJECTED: PASS")
  console.log("DUPLICATE ATTEMPT MADE NO WRITES: PASS")

  // A different request owner cannot take over recovery.
  await assert.rejects(
    recordV3RecoveredLinkTransaction({
      orderId: String(ids[0]),
      owner: "unauthorized-owner",
      expectedPaymentLinkId: linkId,
      verified
    }),
    /ownership or expiry mismatch/
  )

  const afterWrongOwner = await locks.findOne({
    _id: ids[0]
  })

  assert.equal(afterWrongOwner.owner, owner)
  assert.equal(
    afterWrongOwner.ownershipChecks,
    beforeRepeatLock.ownershipChecks
  )

  console.log("WRONG-OWNER RECOVERY REJECTED: PASS")
  console.log("ORIGINAL LOCK OWNERSHIP PRESERVED: PASS")
  await assert.rejects(
    recordV3RecoveredLinkTransaction({
      orderId: String(ids[1]),
      owner,
      expectedPaymentLinkId: linkId,
      verified
    }),
    /eligibility rejected/
  )

  const rejectedOperation = await operations.findOne({
    orderId: ids[1]
  })
  const rejectedOrder = await orders.findOne({ _id: ids[1] })
  const rejectedLock = await locks.findOne({ _id: ids[1] })

  assert.equal(rejectedOperation.status, "reconciliation_required")
  assert.equal(rejectedOperation.squarePaymentLinkId, "")
  assert.equal(rejectedOrder.paymentStatus, "paid")
  assert.equal(rejectedLock.ownershipChecks, 0)

  console.log("PAID-ORDER RECOVERY REJECTED: PASS")
  console.log("REJECTED TRANSACTION DID NOT WRITE: PASS")
  // Two simultaneous recoveries compete for one synthetic order.
  // Both use the same original owner and already-verified
  // synthetic link. No Square API is called.
  const attempts = await Promise.allSettled([
    recordV3RecoveredLinkTransaction({
      orderId: String(ids[2]),
      owner,
      expectedPaymentLinkId: linkId,
      verified
    }),
    recordV3RecoveredLinkTransaction({
      orderId: String(ids[2]),
      owner,
      expectedPaymentLinkId: linkId,
      verified
    })
  ])

  const winners = attempts.filter(x => x.status === "fulfilled")
  const losers = attempts.filter(x => x.status === "rejected")

  assert.equal(
    winners.length,
    1,
    "Exactly one concurrent recovery must succeed"
  )
  assert.equal(
    losers.length,
    1,
    "Exactly one concurrent recovery must fail"
  )
  assert.equal(winners[0].value.paymentLinkRecorded, true)
  assert.equal(winners[0].value.customerPaymentConfirmed, false)

  const concurrentOperation = await operations.findOne({
    orderId: ids[2]
  })
  const concurrentOrder = await orders.findOne({
    _id: ids[2]
  })
  const concurrentLock = await locks.findOne({
    _id: ids[2]
  })

  assert.equal(concurrentOperation.status, "completed")
  assert.equal(concurrentOperation.squarePaymentLinkId, linkId)
  assert.equal(concurrentOperation.squareOrderId, squareOrderId)
  assert.equal(concurrentOperation.requestOwner, owner)
  assert.equal(
    concurrentOperation.squareCreationAttemptClaimedAt.getTime(),
    claim.getTime()
  )
  assert.equal(concurrentOrder.paymentStatus, "unpaid")
  assert.equal(concurrentOrder.status, "payment_required")
  assert.equal(concurrentOrder.v3RecoveryVerificationChecks, 1)
  assert.equal(concurrentLock.owner, owner)
  assert.equal(concurrentLock.expiresAt.getTime(), expiry.getTime())
  assert.equal(concurrentLock.ownershipChecks, 1)

  console.log("CONCURRENT RECOVERY SINGLE WINNER: PASS")
  console.log("CONCURRENT LOSER REJECTED: PASS")
  console.log("CONCURRENT ORDER UNPAID: PASS")
  console.log("CONCURRENT CLAIM AND LOCK PRESERVED: PASS")
  // Fourth fixture: force failure after both transaction fences.
  // MongoDB must roll back the entire transaction.
  const rollbackId = ids[3]
  const beforeRollbackOperation = await operations.findOne({
    orderId: rollbackId
  })
  const beforeRollbackOrder = await orders.findOne({
    _id: rollbackId
  })
  const beforeRollbackLock = await locks.findOne({
    _id: rollbackId
  })

  assert.equal(beforeRollbackOperation.status, "reconciliation_required")
  assert.equal(beforeRollbackOrder.paymentStatus, "unpaid")
  assert.equal(beforeRollbackLock.ownershipChecks, 0)

  process.env.SMART_SHIPPING_V3_TEST_INJECT_FAILURE =
    "after_order_fence"

  try {
    await assert.rejects(
      recordV3RecoveredLinkTransaction({
        orderId: String(rollbackId),
        owner,
        expectedPaymentLinkId: linkId,
        verified
      }),
      /injected rollback after fences/
    )
  } finally {
    delete process.env.SMART_SHIPPING_V3_TEST_INJECT_FAILURE
  }

  const rolledBackOperation = await operations.findOne({
    orderId: rollbackId
  })
  const rolledBackOrder = await orders.findOne({
    _id: rollbackId
  })
  const rolledBackLock = await locks.findOne({
    _id: rollbackId
  })

  assert.equal(rolledBackOperation.status, "reconciliation_required")
  assert.equal(rolledBackOperation.squarePaymentLinkId, "")
  assert.equal(rolledBackOperation.squareOrderId, "")
  assert.equal(rolledBackOperation.paymentUrl, "")
  assert.equal(
    rolledBackOperation.squareCreationAttemptClaimedAt.getTime(),
    claim.getTime()
  )
  assert.equal(rolledBackOperation.requestOwner, owner)

  assert.equal(rolledBackOrder.paymentStatus, "unpaid")
  assert.equal(rolledBackOrder.status, "payment_required")
  assert.equal(
    rolledBackOrder.v3RecoveryVerificationChecks,
    beforeRollbackOrder.v3RecoveryVerificationChecks
  )

  assert.equal(rolledBackLock.owner, owner)
  assert.equal(rolledBackLock.expiresAt.getTime(), expiry.getTime())
  assert.equal(rolledBackLock.ownershipChecks, 0)

  console.log("ROLLBACK AFTER FENCES: PASS")
  console.log("ORDER FENCE ROLLED BACK: PASS")
  console.log("LOCK FENCE ROLLED BACK: PASS")
  console.log("PAYMENT OPERATION UNCHANGED: PASS")
  console.log("CUSTOMER REMAINS UNPAID: PASS")
  // Fifth synthetic fixture: simulate TTL deletion of an expired lock.
  const missingLockId = ids[4]
  const removedLock = await locks.deleteOne({
    _id: missingLockId
  })
  assert.equal(removedLock.deletedCount, 1)

  const beforeMissingLock = await operations.findOne({
    orderId: missingLockId
  })
  const beforeMissingOrder = await orders.findOne({
    _id: missingLockId
  })

  await assert.rejects(
    recordV3RecoveredLinkTransaction({
      orderId: String(missingLockId),
      owner,
      expectedPaymentLinkId: linkId,
      verified
    }),
    /ownership or expiry mismatch/
  )

  const afterMissingLock = await operations.findOne({
    orderId: missingLockId
  })
  const afterMissingOrder = await orders.findOne({
    _id: missingLockId
  })
  const recreatedLock = await locks.findOne({
    _id: missingLockId
  })

  assert.equal(beforeMissingLock.status, "reconciliation_required")
  assert.equal(afterMissingLock.status, "reconciliation_required")
  assert.equal(afterMissingLock.squarePaymentLinkId, "")
  assert.equal(afterMissingLock.squareOrderId, "")
  assert.equal(afterMissingLock.paymentUrl, "")
  assert.equal(
    afterMissingLock.squareCreationAttemptClaimedAt.getTime(),
    claim.getTime()
  )
  assert.equal(afterMissingLock.requestOwner, owner)
  assert.equal(beforeMissingOrder.paymentStatus, "unpaid")
  assert.equal(afterMissingOrder.paymentStatus, "unpaid")
  assert.equal(afterMissingOrder.v3RecoveryVerificationChecks, undefined)
  assert.equal(recreatedLock, null)

  console.log("MISSING EXPIRED LOCK REJECTED: PASS")
  console.log("NO REPLACEMENT LOCK CREATED: PASS")
  console.log("UNPAID ORDER AND CLAIM PRESERVED: PASS")
  console.log("NO SQUARE REQUESTS")
  console.log("NO PROTECTED-ORDER ACCESS")
} finally {
  if (connected) {
    const db = mongoose.connection.db
    // Remove only the two generated synthetic fixture IDs.
    await Order.collection.deleteMany({ _id: { $in: ids } })
    await PaymentOperation.collection.deleteMany({
      orderId: { $in: ids }
    })
    await db.collection("smart_shipping_v3_checkout_locks")
      .deleteMany({ _id: { $in: ids } })
    await mongoose.disconnect()
  }
}